class TestSecurityBoundary:
    def test_provider_receives_full_context(self, tmp_path: Path) -> None:
        """Verify provider.generate() is called with (FullContext, str)."""
        from handoff_agent.cli import cmd_generate
        from handoff_agent.context_builder import FullContext

        repo = tmp_path / "repo"
        init_repo(repo)
        write_file(repo, "main.py", "x = 1")
        commit_all(repo, "initial")

        with patch(
            "handoff_agent.providers.factory._PROVIDERS",
            {"mock": MockProvider},
        ):
            args = _make_args(provider="mock", path=str(repo))
            rc = cmd_generate(args)

        assert rc == 0
        assert len(MockProvider.generate_calls) == 1
        context, prompt = MockProvider.generate_calls[0]

        assert isinstance(context, FullContext)
        assert isinstance(prompt, str)
        assert hasattr(context, "project")
        assert hasattr(context, "git")
        assert hasattr(context, "files")
        assert hasattr(context, "security")

    def test_provider_cannot_access_secrets(self, tmp_path: Path) -> None:
        """Secret files should be excluded from context by SecurityFilter."""
        from handoff_agent.cli import cmd_generate

        repo = tmp_path / "repo"
        init_repo(repo)
        write_file(repo, ".env", "password=abc123")
        write_file(repo, "app.py", "pass")
        commit_all(repo, "initial")

        with patch(
            "handoff_agent.providers.factory._PROVIDERS",
            {"mock": MockProvider},
        ):
            args = _make_args(provider="mock", path=str(repo))
            rc = cmd_generate(args)

        assert rc == 0
        context, prompt = MockProvider.generate_calls[0]
        file_paths = [f.path for f in context.files]
        assert not any("env" in p.lower() for p in file_paths)

    def test_context_has_project_metadata(self, tmp_path: Path) -> None:
        """Context must contain project name, type, and root."""
        from handoff_agent.cli import cmd_generate

        repo = tmp_path / "myproject"
        init_repo(repo)
        write_file(repo, "pyproject.toml", "[project]\nname = 'test'")
        commit_all(repo, "initial")

        with patch(
            "handoff_agent.providers.factory._PROVIDERS",
            {"mock": MockProvider},
        ):
            args = _make_args(provider="mock", path=str(repo))
            rc = cmd_generate(args)

        assert rc == 0
        context, _ = MockProvider.generate_calls[0]
        assert context.project.name == "myproject"
        assert context.project.project_type == "Python"
        assert str(repo) in context.project.root

    def test_context_has_git_info(self, tmp_path: Path) -> None:
        """Context must contain branch, head, clean status."""
        from handoff_agent.cli import cmd_generate

        repo = tmp_path / "repo"
        init_repo(repo)
        write_file(repo, "app.py", "pass")
        commit_all(repo, "initial")

        with patch(
            "handoff_agent.providers.factory._PROVIDERS",
            {"mock": MockProvider},
        ):
            args = _make_args(provider="mock", path=str(repo))
            rc = cmd_generate(args)

        assert rc == 0
        context, _ = MockProvider.generate_calls[0]
        assert context.git.branch == "main"
        assert context.git.head is not None
        assert context.git.clean is True
