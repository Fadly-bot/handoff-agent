def _make_args(**kwargs) -> argparse.Namespace:
    """Build a minimal argparse.Namespace for cmd_generate."""
    defaults = {
        "path": None,
        "provider": None,
        "model": None,
        "output": None,
        "config": None,
        "dry_run": False,
        "commit": False,
        "command": None,
    }
    defaults.update(kwargs)
    return argparse.Namespace(**defaults)


class MockProvider:
    """A mock provider that records calls and returns canned responses."""

    generate_calls: list[tuple[Any, str]] = []

    def __init__(self, config: dict | None = None):
        self.config = config or {}

    def name(self) -> str:
        return "mock"

    def generate(self, context: Any, prompt: str) -> str:
        MockProvider.generate_calls.append((context, prompt))
        return "# Mock Handoff Document\n\nGenerated by mock provider."

    def validate_config(self, config: dict) -> bool:
        return True

    def is_configured(self) -> bool:
        return True


class FailingProvider:
    """A provider that always fails on generate()."""

    def __init__(self, config: dict | None = None):
        self.config = config or {}

    def name(self) -> str:
        return "failing"

    def generate(self, context: Any, prompt: str) -> str:
        raise RuntimeError("Provider deliberately failed")

    def validate_config(self, config: dict) -> bool:
        return True

    def is_configured(self) -> bool:
        return True


@pytest.fixture(autouse=True)
def _clear_mock_calls():
    """Reset MockProvider.generate_calls before each test."""
    MockProvider.generate_calls.clear()
    yield
    MockProvider.generate_calls.clear()


